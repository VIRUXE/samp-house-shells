"""Turn scavengesurvive-mta's generated maps/data/*.lua into a text IPL Ariane can load, plus the RemoveBuilding list.

usage: python tools/make_ipl.py <scavengesurvive-mta> <gta dir> <out dir>
writes <out dir>/scavenge.ipl and <out dir>/removals.json
"""

import json
import math
import re
import struct
import sys
from pathlib import Path

NUM = r"-?\d+(?:\.\d+)?(?:e-?\d+)?"
OBJECT = re.compile(r"^\s*\{ (" + NUM + r"(?:, " + NUM + r"){9}) \},?$")
REMOVAL = re.compile(r"^\s*\{ (" + NUM + r"(?:, " + NUM + r"){4}) \},?$")


def ide_names(gta: Path) -> dict[int, str]:
    names = {}
    for ide in list((gta / "data").rglob("*.ide")) + list((gta / "SAMP").glob("*.ide")):
        section = None
        for line in ide.read_text(errors="ignore").splitlines():
            line = line.split("#")[0].strip()
            if not line:
                continue
            low = line.lower()
            if low in ("objs", "tobj", "anim", "weap", "cars", "peds", "hier", "txdp", "2dfx", "path"):
                section = low
            elif low == "end":
                section = None
            elif section in ("objs", "tobj", "anim"):
                parts = [p.strip() for p in line.split(",")]
                if parts[0].isdigit():
                    names[int(parts[0])] = parts[1]
    return names


def vanilla_instances(gta: Path) -> list[tuple[int, float, float, float]]:
    """(model, x, y, z) of every vanilla placement: text IPLs under data/maps plus the binary stream IPLs in gta3.img."""
    found = []
    for ipl in (gta / "data" / "maps").rglob("*.ipl"):
        section = None
        for line in ipl.read_text(errors="ignore").splitlines():
            line = line.split("#")[0].strip()
            low = line.lower()
            if low in ("inst", "cull", "grge", "enex", "pick", "jump", "tcyc", "auzo", "mult", "cars", "occl", "zone", "path"):
                section = low
            elif low == "end":
                section = None
            elif section == "inst" and line:
                p = [s.strip() for s in line.split(",")]
                found.append((int(p[0]), float(p[3]), float(p[4]), float(p[5])))
    img = (gta / "models" / "gta3.img").read_bytes()
    assert img[:4] == b"VER2"
    for i in range(struct.unpack_from("<I", img, 4)[0]):
        offset, size, _, name = struct.unpack_from("<IHH24s", img, 8 + i * 32)
        if not name.split(b"\0")[0].lower().endswith(b".ipl"):
            continue
        blob = img[offset * 2048 : (offset + size) * 2048]
        if blob[:4] != b"bnry":
            continue
        count, inst_at = struct.unpack_from("<I", blob, 4)[0], struct.unpack_from("<I", blob, 0x1C)[0]
        for k in range(count):
            x, y, z, _qx, _qy, _qz, _qw, model = struct.unpack_from("<7fi", blob, inst_at + k * 40)
            found.append((model, x, y, z))
    return found


def expand_removals(removals: list[dict], vanilla: list[tuple[int, float, float, float]]) -> list[dict]:
    """Ariane caps suppress-world-models at a 250 m radius; turn wider (map-wide) removals into one per instance."""
    out = []
    for r in removals:
        if r["radius"] <= 250:
            out.append(r)
            continue
        for model, x, y, z in vanilla:
            if model == r["model"] and math.dist((x, y, z), (r["x"], r["y"], r["z"])) <= r["radius"]:
                out.append({**r, "x": x, "y": y, "z": z, "radius": 0.5})
    return out


def quat_zxy(rx: float, ry: float, rz: float) -> tuple[float, float, float, float]:
    """MTA/SA-MP object rotation (degrees, applied Z then X then Y) as an IPL quaternion (x, y, z, w).

    SA stores the inverse rotation in IPLs, so the vector part is negated.
    """

    def axis(ax, deg):
        h = math.radians(deg) / 2
        s = math.sin(h)
        return (s * ax[0], s * ax[1], s * ax[2], math.cos(h))

    def mul(a, b):
        ax, ay, az, aw = a
        bx, by, bz, bw = b
        return (aw * bx + ax * bw + ay * bz - az * by, aw * by - ax * bz + ay * bw + az * bx, aw * bz + ax * by - ay * bx + az * bw, aw * bw - ax * bx - ay * by - az * bz)

    q = mul(mul(axis((0, 0, 1), rz), axis((1, 0, 0), rx)), axis((0, 1, 0), ry))
    return (-q[0], -q[1], -q[2], q[3])


def main() -> None:
    repo, gta, out = (Path(a) for a in sys.argv[1:4])
    names = ide_names(gta)
    lines, removals, missing = ["# generated by tools/make_ipl.py from scavengesurvive-mta maps/data", "inst"], [], set()
    for data in sorted((repo / "resources" / "[scavengesurvive]" / "maps" / "data").glob("*.lua")):
        if data.name == "zones.lua":
            continue
        in_removals = False
        for raw in data.read_text().splitlines():
            if raw.strip().startswith("removals"):
                in_removals = True
            m = (REMOVAL if in_removals else OBJECT).match(raw)
            if not m:
                continue
            v = [float(x) for x in m.group(1).split(", ")]
            if in_removals:
                removals.append({"zone": data.stem, "model": int(v[0]), "x": v[1], "y": v[2], "z": v[3], "radius": v[4]})
                continue
            model, x, y, z, rx, ry, rz, _world, interior = int(v[0]), *v[1:9]
            name = names.get(model)
            if name is None:
                missing.add(model)
                continue
            qx, qy, qz, qw = quat_zxy(rx, ry, rz)
            lines.append(f"{model}, {name}, {max(int(interior), 0)}, {x:.4f}, {y:.4f}, {z:.4f}, {qx:.6f}, {qy:.6f}, {qz:.6f}, {qw:.6f}, -1")
    lines.append("end")
    removals = expand_removals(removals, vanilla_instances(gta))
    out.mkdir(parents=True, exist_ok=True)
    (out / "scavenge.ipl").write_text("\n".join(lines) + "\n")
    (out / "removals.json").write_text(json.dumps(removals, indent=1) + "\n")
    print(f"{len(lines) - 3} instances, {len(removals)} removals, models without an IDE name: {sorted(missing)}")


if __name__ == "__main__":
    main()
